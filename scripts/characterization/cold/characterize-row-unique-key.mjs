/**
 * Characterization: row unique-key disambiguation for same-named el-table rows.
 *
 * Asserts that the page-side locator helpers (PAGE_LOCATOR_HELPERS) and the CDP
 * payload builder (BUILD_PAYLOAD_FN) contain the unique-key column priority
 * (customer-number 14-18 digits / unified social-credit code 18 alphanumerics)
 * and emit the row-anchor xpath format
 *   //tr[.//*[normalize-space()=<uniqueKey>]]//button[normalize-space()=<btnText>]
 * rather than pinning a same-named row by positional [N].
 *
 * Pure string/regex assertions — no browser launch.
 *
 *   node scripts/characterization/characterize-row-unique-key.mjs
 */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { PAGE_LOCATOR_HELPERS } from '../../src/cdp/locator-candidates.js';
import { BUILD_PAYLOAD_FN } from '../../src/cdp/inspect-payload-script.js';

const __dirname = dirname(fileURLToPath(import.meta.url));

function ok(name) {
  console.log(`ok: ${name}`);
}

// 1. PAGE_LOCATOR_HELPERS contains the unique-key regexes for table rows.
{
  assert.ok(
    /\/\^\\d\{14,18\}\$\//.test(PAGE_LOCATOR_HELPERS),
    'PAGE_LOCATOR_HELPERS must include /^\\d{14,18}$/ customer-number regex',
  );
  assert.ok(
    /\/\^\[0-9A-Z\]\{18\}\$\//.test(PAGE_LOCATOR_HELPERS),
    'PAGE_LOCATOR_HELPERS must include /^[0-9A-Z]{18}$/ credit-code regex',
  );
  ok('PAGE_LOCATOR_HELPERS unique-key regexes present');
}

// 2. PAGE_LOCATOR_HELPERS table_row_button emits a row-anchor xpath that uses
//    tr[.//*[normalize-space()=<rowText>]] (exact normalize-space match), not a
//    positional [N] pin for the unique-key row.
{
  assert.ok(
    PAGE_LOCATOR_HELPERS.includes("tr[.//*[normalize-space()="),
    'PAGE_LOCATOR_HELPERS table_row_button must build tr[.//*[normalize-space()=...]] anchor',
  );
  // The button leaf uses normalize-space()= for exact button text match.
  assert.ok(
    PAGE_LOCATOR_HELPERS.includes('[normalize-space()=') ,
    'PAGE_LOCATOR_HELPERS must use normalize-space()= exact-match predicate',
  );
  ok('PAGE_LOCATOR_HELPERS row-anchor xpath format (exact normalize-space)');
}

// 3. BUILD_PAYLOAD_FN (CDP inspect payload) contains tableRowIdentityText with
//    the same unique-key priority.
{
  assert.ok(
    BUILD_PAYLOAD_FN.includes('tableRowIdentityText'),
    'BUILD_PAYLOAD_FN must define tableRowIdentityText for row identity extraction',
  );
  assert.ok(
    /\/\^\\d\{14,18\}\$\//.test(BUILD_PAYLOAD_FN),
    'BUILD_PAYLOAD_FN tableRowIdentityText must include /^\\d{14,18}$/ regex',
  );
  assert.ok(
    /\/\^\[0-9A-Z\]\{18\}\$\//.test(BUILD_PAYLOAD_FN),
    'BUILD_PAYLOAD_FN tableRowIdentityText must include /^[0-9A-Z]{18}$/ regex',
  );
  ok('BUILD_PAYLOAD_FN tableRowIdentityText unique-key priority');
}

// 4. Python mirror _locator_helpers_js.py carries the same unique-key fragments
//    (generated by node scripts/_gen_locator_helpers_py.mjs).
{
  const py = readFileSync(
    join(__dirname, '..', 'controller', 'actions', 'js_snippets', '_locator_helpers_js.py'),
    'utf8',
  );
  assert.ok(py.includes('buildLocatorSnap'), 'Python mirror must include buildLocatorSnap');
  assert.ok(
    /\^\\d\{14,18\}\$/.test(py),
    'Python mirror must include ^\\d{14,18}$ customer-number regex',
  );
  assert.ok(
    /\^\[0-9A-Z\]\{18\}\$/.test(py),
    'Python mirror must include ^[0-9A-Z]{18}$ credit-code regex',
  );
  assert.ok(
    py.includes("tr[.//*[normalize-space()="),
    'Python mirror table_row_button must build tr[.//*[normalize-space()=...]] anchor',
  );
  ok('Python _locator_helpers_js.py mirror unique-key parity');
}

// 5. The row-anchor xpath must NOT pin a same-named unique-key row with a bare
//    positional [N] (e.g. (//button[...])[1]). The buildLocatorSnap table_row
//    branches use tr[.//*[normalize-space()=...]] — assert that shape dominates
//    over occurrence pinning for table rows by checking the anchor prefix is
//    present and occurrence pinning ([1]/[2]) is not used inside the tr anchor.
{
  const anchorIdx = PAGE_LOCATOR_HELPERS.indexOf("tr[.//*[normalize-space()=");
  assert.ok(anchorIdx >= 0, 'row-anchor xpath must be present');
  const slice = PAGE_LOCATOR_HELPERS.slice(anchorIdx, anchorIdx + 160);
  assert.ok(
    !/\)\[\d+\]/.test(slice),
    'row-anchor xpath must not occurrence-pin the unique-key row with [N]',
  );
  ok('row-anchor does not occurrence-pin unique-key row');
}

console.log('characterize-row-unique-key: OK');
